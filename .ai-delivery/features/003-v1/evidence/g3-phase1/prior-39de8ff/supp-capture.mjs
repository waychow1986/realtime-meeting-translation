import { chromium } from '/tmp/qa-work/node_modules/playwright/index.mjs';
import fs from 'fs';
const url = process.env.AIDH_SERVICE_WEB_URL;
const b64 = fs.readFileSync('/tmp/ko.mp3').toString('base64');
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await b.newContext();
await ctx.addInitScript({ content: `(()=>{const B64=${JSON.stringify(b64)};
navigator.mediaDevices.getUserMedia = async () => { const ac = new AudioContext({sampleRate:48000}); await ac.resume();
 const bin = Uint8Array.from(atob(B64), c=>c.charCodeAt(0)); const buf = await ac.decodeAudioData(bin.buffer);
 const dst = ac.createMediaStreamDestination(); const sil = ac.createConstantSource(); sil.offset.value=0; sil.connect(dst); sil.start();
 const src = ac.createBufferSource(); src.buffer = buf; src.connect(dst); setTimeout(()=>src.start(), 1500); window.__dur = buf.duration; return dst.stream; };})();` });
const p = await ctx.newPage();
const reqs = [];
p.on('request', r => { if (r.url().includes('/api/')) reqs.push({ t: Date.now(), m: r.method(), u: r.url().replace(url,''), body: r.postData(), h: Object.fromEntries(Object.entries(r.headers()).filter(([k])=>!/cookie|authorization/i.test(k))) }); });
p.on('response', async r => { if (r.url().includes('/api/translations')) { try { const t = await r.text(); reqs.push({ resp: r.status(), ct: r.headers()['content-type'], body: t.slice(0, 600) }); } catch(e) { reqs.push({resp:r.status(), err:String(e).slice(0,100)}); } } });
await p.goto(url); await p.waitForTimeout(1000);
await p.getByRole('button', { name: '知道了' }).click();
await p.locator('#source-microphone').check();
await p.locator('#start-button').click();
await p.waitForTimeout(30000);
const cap = await p.evaluate(() => document.body.innerText.slice(0, 1500));
await p.locator('#stop-button, button:has-text("停止")').first().click().catch(()=>{});
fs.writeFileSync('/tmp/cap.json', JSON.stringify({ reqs, cap }, null, 1));
await b.close();
console.log(reqs.length);
